-- 1) Perfil de cada usuario. El que ya era principal queda como PRINCIPAL; los demás como ADMIN.
DECLARE
  l_existe NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_existe FROM user_tab_columns WHERE table_name = 'FN_ADMIN' AND column_name = 'ROL';
  IF l_existe = 0 THEN
    EXECUTE IMMEDIATE q'[ALTER TABLE fn_admin ADD (rol VARCHAR2(10) DEFAULT 'ADMIN' NOT NULL
                          CONSTRAINT fn_admin_rol_ck CHECK (rol IN ('PRINCIPAL','ADMIN','HOST')))]';
    EXECUTE IMMEDIATE q'[UPDATE fn_admin SET rol = 'PRINCIPAL' WHERE es_principal = 'S']';
    COMMIT;
  END IF;
END;

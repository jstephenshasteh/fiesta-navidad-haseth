-- 2) Tablas de premios
DECLARE
  PROCEDURE crear(p_tabla VARCHAR2, p_sql VARCHAR2) IS
    l_existe NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_existe FROM user_tables WHERE table_name = p_tabla;
    IF l_existe = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
  END;
  PROCEDURE indice(p_nombre VARCHAR2, p_sql VARCHAR2) IS
    l_existe NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_existe FROM user_indexes WHERE index_name = p_nombre;
    IF l_existe = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
  END;
BEGIN
  crear('FN_RONDA', q'[CREATE TABLE fn_ronda (
      id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      evento_id  NUMBER        NOT NULL REFERENCES fn_evento(id),
      nombre     VARCHAR2(120) NOT NULL,
      creado_en  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL)]');
  crear('FN_PUESTO', q'[CREATE TABLE fn_puesto (
      id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ronda_id   NUMBER        NOT NULL REFERENCES fn_ronda(id),
      posicion   NUMBER(3)     NOT NULL,
      premio     VARCHAR2(200),
      CONSTRAINT fn_puesto_uk UNIQUE (ronda_id, posicion))]');
  crear('FN_GANADOR', q'[CREATE TABLE fn_ganador (
      id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      puesto_id   NUMBER       NOT NULL REFERENCES fn_puesto(id),
      invitado_id NUMBER       NOT NULL REFERENCES fn_invitado(id),
      estado      VARCHAR2(10) DEFAULT 'GANADOR' NOT NULL CHECK (estado IN ('GANADOR','AUSENTE')),
      admin_id    NUMBER REFERENCES fn_admin(id),
      sorteado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT fn_ganador_invitado_uk UNIQUE (invitado_id))]');
  indice('FN_GANADOR_PUESTO_UK',
    q'[CREATE UNIQUE INDEX fn_ganador_puesto_uk ON fn_ganador (CASE WHEN estado = 'GANADOR' THEN puesto_id END)]');
END;
/


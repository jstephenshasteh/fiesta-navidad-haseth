-- ---------------------------------------------------------------------
-- Evento (una fila por evento; la app usa el evento marcado ACTIVO = 'S')
-- ---------------------------------------------------------------------
CREATE TABLE FN_EVENTO (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE          VARCHAR2(150)  NOT NULL,
  FECHA_TEXTO     VARCHAR2(80),            -- p. ej. "Viernes 5 de diciembre de 2026"
  DIA             VARCHAR2(5),             -- p. ej. "5"
  MES_CORTO       VARCHAR2(10),            -- p. ej. "DIC"
  HORA            VARCHAR2(30),            -- p. ej. "7:00 p. m."
  LUGAR           VARCHAR2(200),           -- p. ej. "Hotel Marriott Panamá Albrook"
  SALON           VARCHAR2(100),           -- p. ej. "Salón Gran Colón"
  VESTIMENTA      VARCHAR2(80),            -- p. ej. "Black & White"
  PREFIJO_CODIGO  VARCHAR2(10)   DEFAULT 'HAS' NOT NULL,
  TEMA_PASE       VARCHAR2(20)   DEFAULT 'rojo' NOT NULL,  -- rojo | verde
  ASUNTO_CORREO   VARCHAR2(200),
  MENSAJE         VARCHAR2(2000),          -- plantilla con {nombre}, {codigo}, {area}
  ARTE            BLOB,                    -- imagen 1: arte general
  ARTE_MIME       VARCHAR2(50),
  ARTE_NOMBRE     VARCHAR2(200),
  ACTIVO          CHAR(1)        DEFAULT 'S' NOT NULL CHECK (ACTIVO IN ('S','N')),
  CREADO_EN       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- Administradores (quienes usan la app; entran eligiendo su nombre + PIN)
-- ---------------------------------------------------------------------
CREATE TABLE FN_ADMIN (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE          VARCHAR2(120)  NOT NULL,
  PIN_HASH        VARCHAR2(100)  NOT NULL,  -- bcrypt
  ES_PRINCIPAL    CHAR(1)        DEFAULT 'N' NOT NULL CHECK (ES_PRINCIPAL IN ('S','N')),
  ACTIVO          CHAR(1)        DEFAULT 'S' NOT NULL CHECK (ACTIVO IN ('S','N')),
  COLOR           VARCHAR2(9)    DEFAULT '#146B47',
  CREADO_EN       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- Invitados (cargados desde Excel)
-- ---------------------------------------------------------------------
CREATE TABLE FN_INVITADO (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EVENTO_ID        NUMBER         NOT NULL REFERENCES FN_EVENTO(ID),
  CODIGO           VARCHAR2(20)   NOT NULL,         -- visible: HAS-001
  TOKEN_QR         VARCHAR2(64)   NOT NULL,         -- secreto que va dentro del QR
  NOMBRE           VARCHAR2(150)  NOT NULL,
  CORREO           VARCHAR2(150),
  WHATSAPP         VARCHAR2(30),                    -- formato internacional sin +: 50761234567
  AREA             VARCHAR2(100),
  LLEGADA_EN       TIMESTAMP,
  LLEGADA_ADMIN_ID NUMBER REFERENCES FN_ADMIN(ID),
  LLEGADA_VIA      VARCHAR2(10) CHECK (LLEGADA_VIA IN ('QR','NOMBRE')),
  ACTIVO           CHAR(1)        DEFAULT 'S' NOT NULL CHECK (ACTIVO IN ('S','N')),
  CREADO_EN        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FN_INVITADO_CODIGO_UK UNIQUE (EVENTO_ID, CODIGO),
  CONSTRAINT FN_INVITADO_TOKEN_UK  UNIQUE (TOKEN_QR)
);

CREATE INDEX FN_INVITADO_EVENTO_IX ON FN_INVITADO (EVENTO_ID, ACTIVO);
CREATE INDEX FN_INVITADO_NOMBRE_IX ON FN_INVITADO (UPPER(NOMBRE));

-- ---------------------------------------------------------------------
-- Envíos de invitaciones (un registro por invitado y canal)
-- ---------------------------------------------------------------------
CREATE TABLE FN_ENVIO (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  INVITADO_ID     NUMBER         NOT NULL REFERENCES FN_INVITADO(ID),
  CANAL           VARCHAR2(10)   NOT NULL CHECK (CANAL IN ('WHATSAPP','CORREO')),
  ESTADO          VARCHAR2(10)   NOT NULL CHECK (ESTADO IN ('ENVIADO','ERROR')),
  DETALLE         VARCHAR2(1000),           -- mensaje de error o respuesta
  PROVEEDOR_ID    VARCHAR2(200),            -- id del mensaje en 360dialog / SMTP
  ADMIN_ID        NUMBER REFERENCES FN_ADMIN(ID),
  ENVIADO_EN      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX FN_ENVIO_INVITADO_IX ON FN_ENVIO (INVITADO_ID, CANAL);

-- ---------------------------------------------------------------------
-- Bitácora de escaneos (incluye intentos fallidos / duplicados)
-- ---------------------------------------------------------------------
CREATE TABLE FN_ESCANEO (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  INVITADO_ID     NUMBER REFERENCES FN_INVITADO(ID),
  RESULTADO       VARCHAR2(12)   NOT NULL CHECK (RESULTADO IN ('OK','DUPLICADO','INVALIDO')),
  VALOR_LEIDO     VARCHAR2(200),
  ADMIN_ID        NUMBER REFERENCES FN_ADMIN(ID),
  ESCANEADO_EN    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);
